/* Bakes the circuit centrelines into src/12-trackdata.js.
 *
 *   node tools/bake-tracks.js
 *
 * WHY. The track used to ask three.js (CatmullRomCurve3) where its 900
 * centreline samples are, on every load. A different three.js release could
 * return slightly different samples and silently change every lap time. The
 * samples are now plain data in a generated source file, and the vendored
 * r128 is only consulted here, and by test/track-bake.test.js, which checks
 * the committed data still equals a fresh r128 sampling.
 *
 * Numbers are written with String(value), which JavaScript guarantees reads
 * back as exactly the same double.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(REPO, p), 'utf8');
const OUT = path.join(REPO, 'src', '12-trackdata.js');
const SAMPLES = 900;

let three = null;
function loadThree() {
  if (three) return three;
  global.window = global;
  global.self = global;
  new Function(read('vendor/three.min.js'))();
  three = global.THREE;
  return three;
}

/* Sample one circuit exactly as Track did: control rows are [x, z, y], Vector3
   wants (x, y, z); centripetal closed Catmull Rom, 900 evenly spaced points
   (getSpacedPoints returns 901, the last equal to the first, so it is dropped). */
function sampleWithThree(def) {
  const THREE = loadThree();
  const pts = def.control.map((c) => new THREE.Vector3(c[0], c[2], c[1]));
  const curve = new THREE.CatmullRomCurve3(pts, true, 'centripetal', 0.5);
  return curve.getSpacedPoints(SAMPLES).slice(0, SAMPLES);
}

function loadTracks() {
  const THREE = loadThree();
  let body = '';
  for (const f of ['src/05-fpmath.js', 'src/10-core.js', 'src/20-track.js']) body += '\n;/* ' + f + ' */\n' + read(f);
  return new Function('THREE', body + '\nreturn TRACKS;')(THREE);
}

function bake() {
  const tracks = loadTracks();
  let s = '/* GENERATED by tools/bake-tracks.js from the control points in 20-track.js,\n' +
    '   sampled with the vendored three.js r128 CatmullRomCurve3 (centripetal, closed).\n' +
    '   Do not edit by hand: run  node tools/bake-tracks.js  and commit the result.\n' +
    '   test/track-bake.test.js fails if this file and a fresh sampling disagree. */\n' +
    'var TRACK_BAKED = {\n';
  tracks.forEach((def, k) => {
    const p = sampleWithThree(def);
    const col = (key) => '[' + p.map((v) => String(v[key])).join(',') + ']';
    s += '  ' + JSON.stringify(def.geom) + ': {\n    n: ' + SAMPLES + ',\n    x: ' + col('x') +
      ',\n    y: ' + col('y') + ',\n    z: ' + col('z') + '\n  }' + (k < tracks.length - 1 ? ',' : '') + '\n';
  });
  s += '};\n';
  fs.writeFileSync(OUT, s);
  console.log('wrote ' + path.relative(REPO, OUT) + ' (' + Buffer.byteLength(s) + ' bytes)');
}

module.exports = { sampleWithThree };

if (require.main === module) bake();
